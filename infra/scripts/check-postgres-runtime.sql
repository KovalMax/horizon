       OR has_schema_privilege('public', 'CREATE')
       OR has_database_privilege(current_database(), 'CREATE') THEN
        RAISE EXCEPTION 'Runtime has unexpected database privileges';
    END IF;
    BEGIN
        ALTER TABLE public.runtime_grant_fixture ADD COLUMN disallowed integer;
        RAISE EXCEPTION 'Runtime unexpectedly owns a migrated table';
